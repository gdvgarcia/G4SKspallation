/// \file SKActionInitialization.cc
/// \brief Implementation of the SKActionInitialization class

#include "SKActionInitialization.hh"
#include "SKPrimaryGeneratorAction.hh"
#include "SKRunAction.hh"
#include "SKEventAction.hh"
#include "SKSteppingAction.hh"
#include "SKFileReader.hh"
#include "SKDetectorConstruction.hh"

//....oooOO0OOooo........oooOO0OOooo........oooOO0OOooo........oooOO0OOooo......

SKActionInitialization::SKActionInitialization(SKDetectorConstruction* detConstruction)
 : G4VUserActionInitialization(),
   fDetConstruction(detConstruction)
{}

//....oooOO0OOooo........oooOO0OOooo........oooOO0OOooo........oooOO0OOooo......

SKActionInitialization::~SKActionInitialization()
{}

//....oooOO0OOooo........oooOO0OOooo........oooOO0OOooo........oooOO0OOooo......

void SKActionInitialization::BuildForMaster() const
{ // setting user's actions for the master in multi-threading mode
   SKEventAction* eventAction = new SKEventAction;
   SetUserAction(new SKRunAction(eventAction));
}

//....oooOO0OOooo........oooOO0OOooo........oooOO0OOooo........oooOO0OOooo......

void SKActionInitialization::Build() const
{// setting user's actions for the workers in multi-threading mode or for the full run in sequential mode
  SetUserAction(new SKPrimaryGeneratorAction);

  SKEventAction* eventAction = new SKEventAction;
  SetUserAction(eventAction);
  SetUserAction(new SKSteppingAction(fDetConstruction,eventAction));
  
  SetUserAction(new SKRunAction(eventAction));
}  

